from __future__ import annotations

from pathlib import Path
from typing import Iterable

from docx import Document
from docx.enum.text import WD_BREAK
from docx.shared import Inches, Pt

from .schemas import DocumentModel, Element


def build_docx(model: DocumentModel, output_path: str | Path) -> str:
    """Export the canonical model to a semantic DOCX.

    Prioritizes editable heading hierarchy and readable content over exact
    reproduction of PDF pagination. Figure bytes are not embedded yet because
    the current extractor records image metadata/coordinates only.
    """
    output = Path(output_path).expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)

    doc = Document()
    doc.core_properties.title = Path(model.source_file).stem or model.document_id
    doc.core_properties.subject = "Converted from PDF by document-engine"
    doc.core_properties.comments = "Semantic structure generated by document-engine"

    doc.add_heading(Path(model.source_file).stem or "Converted document", level=0)
    doc.add_paragraph(
        f"Source: {model.source_file} | Pages: {model.page_count}",
        style="Subtitle",
    )

    # Use a generated table of contents list. Word's automatic TOC field is not
    # added here because updating field codes varies across office applications.
    if model.toc:
        doc.add_heading("Table of Contents", level=1)
        for item in model.toc:
            p = doc.add_paragraph(style="List Bullet")
            p.paragraph_format.left_indent = Inches(0.2 * max(0, item.level - 1))
            p.add_run(f"{item.title}").bold = item.level == 1
            if item.page_number:
                p.add_run(f"  (PDF page {item.page_number})")
        doc.add_page_break()

    # Place elements in canonical reading order. Tables are rendered as Word
    # tables where the extracted model includes rows.
    table_ids = set()
    for element in model.elements:
        if element.type == "heading":
            level = min(max(element.level or 1, 1), 9)
            doc.add_heading(element.text, level=level)
        elif element.type in ("paragraph", "unknown", "header", "footer"):
            if element.text.strip():
                doc.add_paragraph(element.text)
        elif element.type == "list_item":
            doc.add_paragraph(element.text, style="List Bullet")
        elif element.type == "caption":
            p = doc.add_paragraph()
            p.paragraph_format.keep_with_next = False
            run = p.add_run(element.text)
            run.italic = True
        elif element.type == "table":
            if element.id in table_ids:
                continue
            table_ids.add(element.id)
            rows = element.table.rows if element.table else []
            if rows:
                width = max(len(row) for row in rows)
                table = doc.add_table(rows=0, cols=max(1, width))
                table.style = "Table Grid"
                for row_data in rows:
                    cells = table.add_row().cells
                    for idx in range(width):
                        cells[idx].text = str(row_data[idx]) if idx < len(row_data) else ""
        elif element.type == "figure":
            doc.add_paragraph(
                f"[Figure detected on PDF page {element.page_number}; "
                "image embedding is not yet configured.]"
            )

    doc.save(output)
    return str(output)